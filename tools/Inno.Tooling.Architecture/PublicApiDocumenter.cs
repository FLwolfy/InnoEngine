internal static class PublicApiDocumenter
{
    internal static int Document(string repositoryRoot, IReadOnlyList<string> roots)
    {
        int changedFileCount = 0;
        foreach (string rootName in roots)
        {
            if (string.Equals(rootName, "tools", StringComparison.Ordinal))
            {
                continue;
            }
            string root = Path.Combine(repositoryRoot, rootName);
            if (!Directory.Exists(root))
                continue;
            foreach (string path in Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories))
            {
                if (path.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}", StringComparison.Ordinal) ||
                    path.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
                {
                    continue;
                }
                string source = File.ReadAllText(path);
                if (source.Contains("<auto-generated>", StringComparison.OrdinalIgnoreCase) ||
                    source.Contains("[GeneratedCode", StringComparison.Ordinal))
                {
                    continue;
                }
                SyntaxTree tree = CSharpSyntaxTree.ParseText(source, path: path);
                SyntaxNode rootNode = tree.GetRoot();
                SyntaxNode rewritten = new DocumentationRewriter().Visit(rootNode)!;
                string updated = rewritten.ToFullString();
                if (string.Equals(source, updated, StringComparison.Ordinal))
                    continue;
                File.WriteAllText(path, updated);
                changedFileCount++;
            }
        }
        return changedFileCount;
    }

    private sealed class DocumentationRewriter : CSharpSyntaxRewriter
    {
        public override SyntaxNode? VisitClassDeclaration(ClassDeclarationSyntax node)
            => DocumentType((ClassDeclarationSyntax)base.VisitClassDeclaration(node)!);

        public override SyntaxNode? VisitStructDeclaration(StructDeclarationSyntax node)
            => DocumentType((StructDeclarationSyntax)base.VisitStructDeclaration(node)!);

        public override SyntaxNode? VisitInterfaceDeclaration(InterfaceDeclarationSyntax node)
            => DocumentType((InterfaceDeclarationSyntax)base.VisitInterfaceDeclaration(node)!);

        public override SyntaxNode? VisitRecordDeclaration(RecordDeclarationSyntax node)
            => DocumentType((RecordDeclarationSyntax)base.VisitRecordDeclaration(node)!);

        public override SyntaxNode? VisitEnumDeclaration(EnumDeclarationSyntax node)
            => DocumentType((EnumDeclarationSyntax)base.VisitEnumDeclaration(node)!);

        public override SyntaxNode? VisitDelegateDeclaration(DelegateDeclarationSyntax node)
        {
            node = (DelegateDeclarationSyntax)base.VisitDelegateDeclaration(node)!;
            return ShouldDocument(node)
                ? AddDocumentation(node, DescribeDelegate(node), node.ParameterList.Parameters, node.TypeParameterList, node.ReturnType)
                : node;
        }

        public override SyntaxNode? VisitEnumMemberDeclaration(EnumMemberDeclarationSyntax node)
        {
            node = (EnumMemberDeclarationSyntax)base.VisitEnumMemberDeclaration(node)!;
            if (node.Parent is not EnumDeclarationSyntax parent || !ShouldDocument(parent))
                return node;
            return AddDocumentation(node, DescribeEnumMember(node.Identifier.ValueText));
        }

        public override SyntaxNode? VisitConstructorDeclaration(ConstructorDeclarationSyntax node)
        {
            node = (ConstructorDeclarationSyntax)base.VisitConstructorDeclaration(node)!;
            return ShouldDocument(node)
                ? AddDocumentation(node, DescribeConstructor(node), node.ParameterList.Parameters)
                : node;
        }

        public override SyntaxNode? VisitMethodDeclaration(MethodDeclarationSyntax node)
        {
            node = (MethodDeclarationSyntax)base.VisitMethodDeclaration(node)!;
            return ShouldDocument(node)
                ? AddDocumentation(
                    node,
                    DescribeMethod(node.Identifier.ValueText, node.Parent),
                    node.ParameterList.Parameters,
                    node.TypeParameterList,
                    node.ReturnType)
                : node;
        }

        public override SyntaxNode? VisitOperatorDeclaration(OperatorDeclarationSyntax node)
        {
            node = (OperatorDeclarationSyntax)base.VisitOperatorDeclaration(node)!;
            return ShouldDocument(node)
                ? AddDocumentation(node, DescribeOperator(node.OperatorToken.ValueText), node.ParameterList.Parameters, returnType: node.ReturnType)
                : node;
        }

        public override SyntaxNode? VisitConversionOperatorDeclaration(ConversionOperatorDeclarationSyntax node)
        {
            node = (ConversionOperatorDeclarationSyntax)base.VisitConversionOperatorDeclaration(node)!;
            return ShouldDocument(node)
                ? AddDocumentation(
                    node,
                    $"Converts the supplied value to <see cref=\"{EscapeType(node.Type)}\"/>.",
                    node.ParameterList.Parameters,
                    returnType: node.Type)
                : node;
        }

        public override SyntaxNode? VisitPropertyDeclaration(PropertyDeclarationSyntax node)
        {
            node = (PropertyDeclarationSyntax)base.VisitPropertyDeclaration(node)!;
            return ShouldDocument(node)
                ? AddDocumentation(node, DescribeProperty(node.Identifier.ValueText, node.Type))
                : node;
        }

        public override SyntaxNode? VisitIndexerDeclaration(IndexerDeclarationSyntax node)
        {
            node = (IndexerDeclarationSyntax)base.VisitIndexerDeclaration(node)!;
            return ShouldDocument(node)
                ? AddDocumentation(node, "Gets or sets the value identified by the supplied index.", node.ParameterList.Parameters)
                : node;
        }

        public override SyntaxNode? VisitEventDeclaration(EventDeclarationSyntax node)
        {
            node = (EventDeclarationSyntax)base.VisitEventDeclaration(node)!;
            return ShouldDocument(node)
                ? AddDocumentation(node, DescribeEvent(node.Identifier.ValueText))
                : node;
        }

        public override SyntaxNode? VisitEventFieldDeclaration(EventFieldDeclarationSyntax node)
        {
            node = (EventFieldDeclarationSyntax)base.VisitEventFieldDeclaration(node)!;
            if (!ShouldDocument(node))
                return node;
            string name = node.Declaration.Variables.FirstOrDefault()?.Identifier.ValueText ?? "state";
            return AddDocumentation(node, DescribeEvent(name));
        }

        public override SyntaxNode? VisitFieldDeclaration(FieldDeclarationSyntax node)
        {
            node = (FieldDeclarationSyntax)base.VisitFieldDeclaration(node)!;
            if (!ShouldDocument(node))
                return node;
            string name = node.Declaration.Variables.FirstOrDefault()?.Identifier.ValueText ?? "value";
            return AddDocumentation(node, DescribeField(name));
        }

        private static T DocumentType<T>(T node)
            where T : TypeDeclarationSyntax
        {
            if (!ShouldDocument(node))
                return node;
            SeparatedSyntaxList<ParameterSyntax> parameters = node switch
            {
                ClassDeclarationSyntax declaration when declaration.ParameterList is not null => declaration.ParameterList.Parameters,
                StructDeclarationSyntax declaration when declaration.ParameterList is not null => declaration.ParameterList.Parameters,
                RecordDeclarationSyntax record when record.ParameterList is not null => record.ParameterList.Parameters,
                _ => default
            };
            return AddDocumentation(node, DescribeType(node.Identifier.ValueText, node), parameters, node.TypeParameterList);
        }

        private static EnumDeclarationSyntax DocumentType(EnumDeclarationSyntax node)
            => ShouldDocument(node)
                ? AddDocumentation(node, DescribeType(node.Identifier.ValueText, node))
                : node;

        private static bool ShouldDocument(MemberDeclarationSyntax node)
        {
            if (HasDocumentation(node))
                return true;
            return RequiresDocumentation(node);
        }

        private static bool RequiresDocumentation(MemberDeclarationSyntax node)
        {
            if (node.Parent is InterfaceDeclarationSyntax)
                return true;
            return node.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.PublicKeyword)) ||
                   node.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.ProtectedKeyword));
        }

        private static bool HasDocumentation(SyntaxNode node)
            => node.GetLeadingTrivia().Any(static trivia => trivia.GetStructure() is DocumentationCommentTriviaSyntax);

        private static T AddDocumentation<T>(
            T node,
            string summary,
            SeparatedSyntaxList<ParameterSyntax> parameters = default,
            TypeParameterListSyntax? typeParameters = null,
            TypeSyntax? returnType = null)
            where T : MemberDeclarationSyntax
        {
            if (HasDocumentation(node))
            {
                string existing = node.GetLeadingTrivia().ToFullString();
                if (!RequiresDocumentation(node) && ContainsGeneratedFallback(existing))
                    return RemoveDocumentation(node);
                return RewriteGenericDocumentation(node, summary, parameters, typeParameters, returnType);
            }
            string indentation = GetIndentation(node);
            var builder = new StringBuilder();
            AppendElement(builder, indentation, "summary", summary);
            if (typeParameters is not null)
            {
                foreach (TypeParameterSyntax parameter in typeParameters.Parameters)
                {
                    AppendElement(
                        builder,
                        indentation,
                        $"typeparam name=\"{parameter.Identifier.ValueText}\"",
                        $"The caller-selected {Humanize(parameter.Identifier.ValueText)} type whose declared constraints are enforced by this operation.",
                        "typeparam");
                }
            }
            foreach (ParameterSyntax parameter in parameters)
            {
                string name = parameter.Identifier.ValueText;
                AppendElement(
                    builder,
                    indentation,
                    $"param name=\"{name}\"",
                    DescribeParameter(parameter, GetOperationName(node)),
                    "param");
            }
            if (returnType is not null && !string.Equals(returnType.ToString(), "void", StringComparison.Ordinal))
            {
                AppendElement(builder, indentation, "returns", DescribeReturn(GetOperationName(node), returnType));
            }
            SyntaxTriviaList documentation = SyntaxFactory.ParseLeadingTrivia(builder.ToString());
            SyntaxTriviaList leading = node.GetLeadingTrivia();
            while (leading.Count > 0 && leading[^1].IsKind(SyntaxKind.WhitespaceTrivia))
                leading = leading.RemoveAt(leading.Count - 1);
            return node.WithLeadingTrivia(leading.AddRange(documentation));
        }

        private static T RemoveDocumentation<T>(T node)
            where T : SyntaxNode
        {
            SyntaxTriviaList leading = SyntaxFactory.TriviaList(node.GetLeadingTrivia().Where(
                static trivia => trivia.GetStructure() is not DocumentationCommentTriviaSyntax));
            return node.WithLeadingTrivia(leading);
        }

        private static T RewriteGenericDocumentation<T>(
            T node,
            string summary,
            SeparatedSyntaxList<ParameterSyntax> parameters,
            TypeParameterListSyntax? typeParameters,
            TypeSyntax? returnType)
            where T : SyntaxNode
        {
            string leading = node.GetLeadingTrivia().ToFullString();
            if (!ContainsPlaceholder(leading))
                return node;
            string newline = leading.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
            string rewritten = RewriteElement(leading, "summary", null, summary, newline);
            foreach (ParameterSyntax parameter in parameters)
            {
                string name = parameter.Identifier.ValueText;
                rewritten = RewriteElement(
                    rewritten,
                    "param",
                    name,
                    DescribeParameter(parameter, GetOperationName(node)),
                    newline);
            }
            if (typeParameters is not null)
            {
                foreach (TypeParameterSyntax parameter in typeParameters.Parameters)
                {
                    string name = parameter.Identifier.ValueText;
                    rewritten = RewriteElement(
                        rewritten,
                        "typeparam",
                        name,
                        $"The caller-selected {Humanize(name)} type whose declared constraints are enforced by this operation.",
                        newline);
                }
            }
            if (returnType is not null && !string.Equals(returnType.ToString(), "void", StringComparison.Ordinal))
            {
                rewritten = RewriteElement(
                    rewritten,
                    "returns",
                    null,
                    DescribeReturn(GetOperationName(node), returnType),
                    newline);
            }
            else if (node is BaseTypeDeclarationSyntax or ConstructorDeclarationSyntax)
            {
                rewritten = RemoveElement(rewritten, "returns", null, newline);
            }
            return node.WithLeadingTrivia(SyntaxFactory.ParseLeadingTrivia(rewritten));
        }

        private static string RewriteElement(
            string documentation,
            string element,
            string? name,
            string replacement,
            string newline)
        {
            string opening = name is null
                ? $"/// <{element}>"
                : $"/// <{element} name=\"{name}\">";
            string closing = $"/// </{element}>";
            List<string> lines = documentation.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n').ToList();
            for (int index = 0; index < lines.Count; index++)
            {
                if (!string.Equals(lines[index].TrimStart(), opening, StringComparison.Ordinal))
                    continue;
                int end = index + 1;
                while (end < lines.Count && !string.Equals(lines[end].TrimStart(), closing, StringComparison.Ordinal))
                    end++;
                if (end >= lines.Count)
                    return documentation;
                string content = string.Join('\n', lines.Skip(index + 1).Take(end - index - 1));
                if (!ContainsPlaceholder(content))
                    return documentation;
                string indentation = lines[index][..^lines[index].TrimStart().Length];
                lines.RemoveRange(index + 1, end - index - 1);
                lines.Insert(index + 1, $"{indentation}/// {replacement}");
                return string.Join(newline, lines);
            }
            return documentation;
        }

        private static string RemoveElement(
            string documentation,
            string element,
            string? name,
            string newline)
        {
            string opening = name is null
                ? $"/// <{element}>"
                : $"/// <{element} name=\"{name}\">";
            string closing = $"/// </{element}>";
            List<string> lines = documentation.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n').ToList();
            for (int index = 0; index < lines.Count; index++)
            {
                if (!string.Equals(lines[index].TrimStart(), opening, StringComparison.Ordinal))
                    continue;
                int end = index + 1;
                while (end < lines.Count && !string.Equals(lines[end].TrimStart(), closing, StringComparison.Ordinal))
                    end++;
                if (end >= lines.Count)
                    return documentation;
                lines.RemoveRange(index, end - index + 1);
                return string.Join(newline, lines);
            }
            return documentation;
        }

