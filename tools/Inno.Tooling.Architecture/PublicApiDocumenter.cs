        private static string GetOperationName(SyntaxNode node)
            => node switch
            {
                MethodDeclarationSyntax method => method.Identifier.ValueText,
                ConstructorDeclarationSyntax constructor => constructor.Identifier.ValueText,
                DelegateDeclarationSyntax callback => callback.Identifier.ValueText,
                OperatorDeclarationSyntax operation => operation.OperatorToken.ValueText,
                ConversionOperatorDeclarationSyntax => "Convert",
                _ => "operation"
            };

        private static void AppendElement(
            StringBuilder builder,
            string indentation,
            string opening,
            string content,
            string? closing = null)
        {
            builder.Append(indentation).Append("/// <").Append(opening).AppendLine(">");
            builder.Append(indentation).Append("/// ").AppendLine(content);
            builder.Append(indentation).Append("/// </").Append(closing ?? opening).AppendLine(">");
        }

        private static string GetIndentation(SyntaxNode node)
        {
            SyntaxTrivia whitespace = node.GetLeadingTrivia()
                .LastOrDefault(static trivia => trivia.IsKind(SyntaxKind.WhitespaceTrivia));
            return whitespace.ToString();
        }

