        private static string DescribeUnclassifiedParameter(ParameterSyntax parameter, string operationName)
        {
            string name = parameter.Identifier.ValueText;
            string type = parameter.Type?.ToString() ?? string.Empty;
            if (type is "bool" or "bool?")
                return $"Whether {Humanize(name)} behavior is enabled while {Humanize(operationName)} executes.";
            if (type is "string" or "string?")
                return $"The {Humanize(name)} text validated by the {Humanize(operationName)} operation.";
            if (type.Contains("Action", StringComparison.Ordinal) || type.Contains("Func", StringComparison.Ordinal))
                return $"The callback invoked by {Humanize(operationName)} within the operation's owned lifetime.";
            return $"The {Humanize(name)} consumed by {Humanize(operationName)}; ownership remains with the caller unless explicitly stated otherwise.";
        }

        private static string DescribeEvent(string name)
        {
            string subject = name.EndsWith("Changed", StringComparison.Ordinal) && name.Length > "Changed".Length
                ? Humanize(name[..^"Changed".Length])
                : Humanize(name);
            return $"Occurs after the observable {subject} state changes.";
        }

        private static string DescribeReturn(string operationName, TypeSyntax returnType)
        {
            string type = returnType.ToString();
            if (type == "bool")
                return operationName.StartsWith("Try", StringComparison.Ordinal)
                    ? "<see langword=\"true\"/> when the requested result was produced; otherwise, <see langword=\"false\"/>."
                    : "<see langword=\"true\"/> when the documented condition is satisfied; otherwise, <see langword=\"false\"/>.";
            if (type == "string")
                return "The validated text representation owned by the caller.";
            if (type is "float" or "double" or "int" or "long")
                return "The scalar result calculated from the supplied inputs.";
            if (type.Contains("Task", StringComparison.Ordinal))
                return "An asynchronous operation that completes after all requested work has finished.";
            if (type.Contains("IReadOnly", StringComparison.Ordinal) || type.EndsWith("[]", StringComparison.Ordinal))
                return "An immutable snapshot of the values selected by the operation.";
            return $"The validated {Humanize(type)} that represents the completed operation."
                .Replace("<", "", StringComparison.Ordinal)
                .Replace(">", "", StringComparison.Ordinal);
        }

        private static string EscapeType(TypeSyntax type)
            => type.ToString().Replace("<", "{", StringComparison.Ordinal).Replace(">", "}", StringComparison.Ordinal);

        private static string Humanize(string value)
        {
            if (string.IsNullOrWhiteSpace(value))
                return "value";
            var builder = new StringBuilder(value.Length + 8);
            for (int index = 0; index < value.Length; index++)
            {
                char character = value[index];
                if (character == '_')
                {
                    builder.Append(' ');
                    continue;
                }
                if (index > 0 && char.IsUpper(character) && char.IsLower(value[index - 1]))
                    builder.Append(' ');
                builder.Append(char.ToLowerInvariant(character));
            }
            return builder.ToString();
        }
