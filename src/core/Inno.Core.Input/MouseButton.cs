namespace Inno.Core.Input;

/// <summary>
/// Identifies the supported mouse button values for this contract.
/// </summary>
public enum MouseButton
{
    /// <summary>
    /// The left key.
    /// </summary>
    Left = 0,
    /// <summary>
    /// The right key.
    /// </summary>
    Right = 1,
    /// <summary>
    /// The middle key.
    /// </summary>
    Middle = 2,
    /// <summary>
    /// The xbutton1 key.
    /// </summary>
    XButton1 = 3,
    /// <summary>
    /// The xbutton2 key.
    /// </summary>
    XButton2 = 4
}