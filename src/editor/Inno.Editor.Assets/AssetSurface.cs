namespace Inno.Editor.Assets;

/// <summary>Provides strongly typed interaction surfaces owned by the Asset editor feature.</summary>
public static class AssetSurface
{
    /// <summary>Identifies the Asset Browser view.</summary>
    public sealed class Browser;

    /// <summary>Identifies an Asset Browser entry context menu.</summary>
    public sealed class ContextMenu;

    /// <summary>Identifies an asset-reference property target.</summary>
    public sealed class Reference;
}
