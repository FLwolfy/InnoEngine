namespace Inno.Editor.HotKeys;

/// <summary>
/// Defines stable identifiers for built-in editor commands.
/// </summary>
public static class EditorHotKeyCommands
{
    /// <summary>Saves the active editor document.</summary>
    public const string Save = "file.save";

    /// <summary>Renames the current selection.</summary>
    public const string Rename = "edit.rename";

    /// <summary>Deletes the current selection.</summary>
    public const string Delete = "edit.delete";
}
